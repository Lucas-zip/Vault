package com.projeto.vault.enums;

/**
 * Tipo da categoria, usado para diferenciar categorias de receita
 * e de despesa.
 *
 * <ul>
 *   <li>INCOME - categoria usada para receitas (ex: Salário, Freelance).</li>
 *   <li>EXPENSE - categoria usada para despesas (ex: Alimentação, Transporte).</li>
 * </ul>
 */
public enum CategoryType {
    INCOME,
    EXPENSE
}
