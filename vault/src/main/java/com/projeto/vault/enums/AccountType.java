package com.projeto.vault.enums;

/**
 * Tipos de conta financeira que um usuário pode cadastrar.
 *
 * <ul>
 *   <li>CHECKING - conta corrente</li>
 *   <li>SAVINGS - poupança</li>
 *   <li>WALLET - carteira digital / dinheiro em espécie</li>
 *   <li>CREDIT_CARD - cartão de crédito</li>
 *   <li>INVESTMENT - conta de investimentos</li>
 * </ul>
 */
public enum AccountType {
    CHECKING,
    SAVINGS,
    WALLET,
    CREDIT_CARD,
    INVESTMENT
}
